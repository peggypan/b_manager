function memberOrderToReceiptStatus(status: MemberOrderStatus): ReceiptStatus {
  switch (status) {
    case 'paid':
      return 'confirmed';
    case 'pending':
      return 'pending';
    case 'refunded':
      return 'refunded';
    case 'closed':
      return 'cancelled';
    default:
      return 'pending';
  }
}

function memberOrderToReceipt(o: MemberOrder): PaymentReceipt {
  const receiptStatus = memberOrderToReceiptStatus(o.status);
  return {
    id: `pr_${o.id}`,
    receiptNo: o.orderNo.replace(/^M/, 'SK'),
    bizType: 'membership',
    bizTitle: `会员 · ${o.planName}`,
    payerName: o.nickname,
    payerUserId: o.userId,
    amount: o.amount,
    payChannel: o.payChannel,
    status: receiptStatus,
    memberOrderId: o.id,
    paidAt: o.paidAt,
    confirmedAt: receiptStatus === 'confirmed' ? o.paidAt : undefined,
    remark: o.remark,
    createdAt: o.createdAt,
  };
}

